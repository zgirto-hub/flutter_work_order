enum AutoSaveStatus { idle, saving, saved, error }

class AddWorkOrderScreen extends StatefulWidget {
  final WorkOrder? workOrder;
  final String? autoGeneratedJobNo;
  final String? prefillTitle;
  final String? prefillLocation;
  final String? sourceRequestId;
  final int initialTab;
  final String userRole;

  const AddWorkOrderScreen({
    super.key,
    this.workOrder,
    this.autoGeneratedJobNo,
    this.prefillTitle,
    this.prefillLocation,
    this.sourceRequestId,
    this.initialTab = 0,
    this.userRole = 'admin',
  });

  @override
  State<AddWorkOrderScreen> createState() => _AddWorkOrderScreenState();
}

class _AddWorkOrderScreenState extends State<AddWorkOrderScreen> {
  final UserService _userService = UserService();
  final DepartmentService _departmentService = DepartmentService();
  final WorkOrderService _service = WorkOrderService();
  final _formKey = GlobalKey<FormState>();

  final _titleFocusNode = FocusNode();
  final _descriptionFocusNode = FocusNode();
  final _locationFocusNode = FocusNode();
  final _mobileFocusNode = FocusNode();

  List<AppUser> _employees = [];
  List<String> _selectedEmployeeIds = [];

  final TextEditingController jobNoController = TextEditingController();
  final TextEditingController clientController = TextEditingController();
  final TextEditingController descriptionController = TextEditingController();
  final TextEditingController locationController = TextEditingController();
  final TextEditingController mobileController = TextEditingController();
  String selectedDepartment = "General";
  String selectedDepartmentId = '';

  String selectedStatus = "Pending";
  String selectedType = "Technical";
  List<Department> _departments = [];

  // Activity tab state
  int _tabIndex = 0;
  bool _activityViewed = false;
  List<WorkOrderComment> _comments = [];
  List<WorkOrderAttachment> _attachments = [];
  bool _commentsLoading = false;
  bool _refreshing = false;
  bool _sending = false;
  bool _roleLoaded = false;
  String _userRole = 'admin';
  bool _isTechnician = false;
  bool _fieldHasFocus = false;
  bool _commentHasFocus = false;
  final TextEditingController _commentCtrl = TextEditingController();
  final FocusNode _commentFocusNode = FocusNode();
  final ScrollController _activityScrollCtrl = ScrollController();
  PlatformFile? _pendingAttachment;

  // Auto-save state
  Timer? _autoSaveTimer;
  AutoSaveStatus _autoSaveStatus = AutoSaveStatus.idle;
  bool _isAutoSaving = false;
  bool _hasAutoSaved = false;
  Map<String, dynamic>? _lastSavedSnapshot;
  Map<String, dynamic>? _originalSnapshot;

  static const List<String> _allowedTypes = [
    "Technical",
    "Inspection",
    "Other",
  ];

  static const List<String> _allowedStatuses = [
    "Pending",
    "In Progress",
    "Closed",
  ];

  bool get _isReporter => _roleLoaded && _userRole == 'reporter';

  /// Track focus & scroll the focused field into view (iOS PWA keyboard fix).
  void _ensureVisible(FocusNode node) {
    node.addListener(() {
      final anyFocused = _titleFocusNode.hasFocus ||
          _descriptionFocusNode.hasFocus ||
          _locationFocusNode.hasFocus ||
          _mobileFocusNode.hasFocus;
      if (_fieldHasFocus != anyFocused) {
        setState(() => _fieldHasFocus = anyFocused);
      }
      if (node.hasFocus && node.context != null) {
        Future.delayed(const Duration(milliseconds: 400), () {
          if (node.hasFocus && node.context != null) {
            Scrollable.ensureVisible(
              node.context!,
              alignment: 0.3,
              duration: const Duration(milliseconds: 300),
              curve: Curves.easeInOut,
            );
          }
        });
      }
    });
  }

  @override
  void initState() {
    super.initState();
    _ensureVisible(_titleFocusNode);
    _ensureVisible(_descriptionFocusNode);
    _ensureVisible(_locationFocusNode);
    _ensureVisible(_mobileFocusNode);
    _commentFocusNode.addListener(() {
      if (_commentHasFocus != _commentFocusNode.hasFocus) {
        setState(() => _commentHasFocus = _commentFocusNode.hasFocus);
      }
    });
    _loadUserRole();
    if (widget.workOrder != null) {
      jobNoController.text = widget.workOrder!.jobNo;
      clientController.text = widget.workOrder!.title;
      descriptionController.text = widget.workOrder!.description;
      locationController.text = widget.workOrder!.location;
      mobileController.text = widget.workOrder!.mobileNumber ?? '';
      selectedDepartment = widget.workOrder!.department;
      selectedDepartmentId = widget.workOrder!.departmentId;
      selectedStatus = _allowedStatuses.contains(widget.workOrder!.status)
          ? widget.workOrder!.status
          : "Pending";
      selectedType = _allowedTypes.contains(widget.workOrder!.type)
          ? widget.workOrder!.type
          : "Technical";
      _tabIndex = widget.initialTab;
      if (widget.initialTab == 1) _activityViewed = true;
      _loadComments();
      WidgetsBinding.instance.addPostFrameCallback((_) {
        _originalSnapshot = _formSnapshot();
        _lastSavedSnapshot = Map.from(_originalSnapshot!);
        _attachAutoSaveListeners();
      });
    } else {
      jobNoController.text = widget.autoGeneratedJobNo ?? "";
      if (widget.prefillTitle != null) clientController.text = widget.prefillTitle!;
      if (widget.prefillLocation != null) locationController.text = widget.prefillLocation!;
      selectedDepartment = 'General';
      mobileController.text = '';
    }
  }

Future<void> _loadDepartments() async {
  try {
    List<Department> departments;

    if (_userRole == 'admin') {
      departments = await _departmentService.fetchDepartments(isActive: true);
    } else {
      // Non-admin: fetch only allowed target departments based on routing rules
      final currentUser = await _userService.fetchCurrentUser();
      final userDeptId = currentUser?.departmentId;
      if (currentUser != null && userDeptId != null && userDeptId.isNotEmpty) {
        final routeService = DepartmentRouteService();
        departments = await routeService.fetchTargetDepartments(userDeptId);
        // Ensure technician's own department is in the list
        if (_isTechnician && !departments.any((d) => d.id == userDeptId)) {
          final allDepts = await _departmentService.fetchDepartments(isActive: true);
          final own = allDepts.where((d) => d.id == userDeptId).firstOrNull;
          if (own != null) departments.add(own);
        }
      } else {
        // Fallback: show all if user has no department set
        departments = await _departmentService.fetchDepartments(isActive: true);
      }
    }

    if (mounted) {
      setState(() {
        _departments = departments..sort((a, b) => a.name.compareTo(b.name));
        // Sync selected department: try by name, then by ID, then default to first
        final matchByName = _departments.where((d) => d.name == selectedDepartment).firstOrNull;
        if (matchByName != null) {
          selectedDepartmentId = matchByName.id;
        } else if (selectedDepartmentId.isNotEmpty) {
          final matchById = _departments.where((d) => d.id == selectedDepartmentId).firstOrNull;
          if (matchById != null) {
            selectedDepartment = matchById.name;
          } else if (_departments.isNotEmpty) {
            selectedDepartment = _departments.first.name;
            selectedDepartmentId = _departments.first.id;
          }
        } else if (_departments.isNotEmpty) {
          selectedDepartment = _departments.first.name;
          selectedDepartmentId = _departments.first.id;
        }
      });
      _loadEmployees();
    }
  } catch (_) {}
}

  Future<void> _loadUserRole() async {
    try {
      final email = Supabase.instance.client.auth.currentUser?.email ?? '';
      if (email.isEmpty) {
        if (mounted) {
          setState(() {
            _roleLoaded = true;
            _userRole = 'admin';
          });
        }
        return;
      }
      final res = await http.get(
        Uri.parse('${AppConfig.baseUrl}/user-role?email=${Uri.encodeComponent(email)}'),
      );
      if (res.statusCode == 200) {
        final data = jsonDecode(res.body);
        final role = data['user_type'] ?? 'admin';
        if (!mounted) return;
        setState(() {
          _roleLoaded = true;
          _userRole = role;
        });
        if (role == 'reporter') {
          _loadUserProfile(email);
        } else if (role == 'technician') {
          _isTechnician = true;
          final currentUser = await _userService.fetchCurrentUser();
          if (currentUser != null && currentUser.departmentId != null && currentUser.departmentId!.isNotEmpty) {
            final deptId = currentUser.departmentId!;
            // Resolve department name: try user profile, then fetch by ID
            String deptName = currentUser.departments.isNotEmpty
                ? currentUser.departments.first
                : '';
            if (deptName.isEmpty) {
              try {
                final allDepts = await _departmentService.fetchDepartments(isActive: true);
                final match = allDepts.where((d) => d.id == deptId).firstOrNull;
                if (match != null) deptName = match.name;
              } catch (_) {}
            }
            if (mounted) {
              setState(() {
                if (widget.workOrder == null) {
                  selectedDepartmentId = deptId;
                  if (deptName.isNotEmpty) selectedDepartment = deptName;
                }
              });
              _loadEmployees(departmentId: widget.workOrder?.departmentId ?? deptId);
            }
          }
        }
      } else {
        if (!mounted) return;
        setState(() {
          _roleLoaded = true;
          _userRole = 'admin';
        });
      }
    } catch (_) {
      if (!mounted) return;
      setState(() {
        _roleLoaded = true;
        _userRole = 'admin';
      });
    }
    // Load departments after role is known (routing rules depend on role)
    _loadDepartments();
  }

  Future<void> _loadUserProfile(String email) async {
    if (email.isEmpty) return;
    try {
      final res = await http.get(
        Uri.parse('${AppConfig.baseUrl}/users/me?email=${Uri.encodeComponent(email)}'),
      );
      if (res.statusCode == 200 && mounted) {
        final data = jsonDecode(res.body);
        final user = data['user'];
        if (user != null) {
          setState(() {
            mobileController.text = (user['mobile'] ?? '').toString();
          });
        }
      }
    } catch (_) {}
  }

  @override
  void dispose() {
    _autoSaveTimer?.cancel();
    clientController.removeListener(_onFormFieldChanged);
    descriptionController.removeListener(_onFormFieldChanged);
    locationController.removeListener(_onFormFieldChanged);
    mobileController.removeListener(_onFormFieldChanged);
    _titleFocusNode.dispose();
    _descriptionFocusNode.dispose();
    _locationFocusNode.dispose();
    _mobileFocusNode.dispose();
    jobNoController.dispose();
    clientController.dispose();
    descriptionController.dispose();
    locationController.dispose();
    mobileController.dispose();
    _commentCtrl.dispose();
    _commentFocusNode.dispose();
    _activityScrollCtrl.dispose();
    super.dispose();
  }

  // ── Auto-save helpers ──────────────────────────────────────────────

  Map<String, dynamic> _formSnapshot() {
    return {
      'title': clientController.text.trim(),
      'description': descriptionController.text.trim(),
      'location': locationController.text.trim(),
      'mobile_number': mobileController.text.trim(),
      'department_id': selectedDepartmentId,
      'status': selectedStatus,
      'type': selectedType,
      'assigned_technician_ids': List<String>.from(_selectedEmployeeIds)..sort(),
    };
  }

  bool get _hasChanges {
    if (_lastSavedSnapshot == null) return false;
    final current = _formSnapshot();
    if (current.length != _lastSavedSnapshot!.length) return true;
    for (final key in current.keys) {
      final a = current[key];
      final b = _lastSavedSnapshot![key];
      if (a is List && b is List) {
        if (a.length != b.length || a.join(',') != b.join(',')) return true;
      } else if (a != b) {
        return true;
      }
    }
    return false;
  }

  void _attachAutoSaveListeners() {
    if (widget.workOrder == null) return;
    clientController.addListener(_onFormFieldChanged);
    descriptionController.addListener(_onFormFieldChanged);
    locationController.addListener(_onFormFieldChanged);
    mobileController.addListener(_onFormFieldChanged);
  }

  void _onFormFieldChanged() {
    if (widget.workOrder == null) return;
    if (_isReporter) return;
    if (!_roleLoaded) return;
    if (!_hasChanges) return;

    _autoSaveTimer?.cancel();
    _autoSaveTimer = Timer(const Duration(milliseconds: 1500), _performAutoSave);
  }

  Future<void> _performAutoSave() async {
    if (!mounted) return;
    if (_isAutoSaving) return;
    if (widget.workOrder == null) return;
    if (_isReporter) return;
    if (!_hasChanges) return;

    _isAutoSaving = true;
    setState(() => _autoSaveStatus = AutoSaveStatus.saving);

    try {
      final now = DateTime.now().toUtc().toIso8601String();
      final workOrder = WorkOrder(
        id: widget.workOrder!.id,
        jobNo: jobNoController.text.trim(),
        title: clientController.text.trim(),
        status: selectedStatus,
        description: descriptionController.text.trim(),
        location: locationController.text.trim(),
        mobileNumber: mobileController.text.trim(),
        departmentName: selectedDepartment,
        departmentId: selectedDepartmentId,
        type: selectedType,
        dateCreated: widget.workOrder!.dateCreated,
        dateModified: now,
        assignedTechnicians: _selectedEmployeeIds
            .map((id) => TechnicianAssignment(id: id, fullName: ''))
            .toList(),
      );

      await _service.updateWorkOrder(workOrder);

      if (!mounted) return;
      _lastSavedSnapshot = _formSnapshot();
      _hasAutoSaved = true;
      setState(() => _autoSaveStatus = AutoSaveStatus.saved);

      Future.delayed(const Duration(seconds: 2), () {
        if (mounted && _autoSaveStatus == AutoSaveStatus.saved) {
          setState(() => _autoSaveStatus = AutoSaveStatus.idle);
        }
      });
    } catch (_) {
      if (!mounted) return;
      setState(() => _autoSaveStatus = AutoSaveStatus.error);
    } finally {
      _isAutoSaving = false;
    }
  }

  Widget _buildAutoSaveIndicator() {
    if (widget.workOrder == null) return const SizedBox.shrink();

    final showUndo = _canUndo && _autoSaveStatus != AutoSaveStatus.saving;
    final showStatus = _autoSaveStatus != AutoSaveStatus.idle;

    if (!showStatus && !showUndo) return const SizedBox.shrink();

    return Row(
      mainAxisSize: MainAxisSize.min,
      children: [
        if (showStatus) ...[
          if (_autoSaveStatus == AutoSaveStatus.saving)
            SizedBox(
              width: 12,
              height: 12,
              child: CircularProgressIndicator(
                strokeWidth: 1.5,
                color: AppColors.textTertiary,
              ),
            )
          else if (_autoSaveStatus == AutoSaveStatus.saved)
            Icon(Icons.cloud_done_outlined, size: 14, color: AppColors.closedText)
          else if (_autoSaveStatus == AutoSaveStatus.error)
            Icon(Icons.cloud_off_outlined, size: 14, color: AppColors.dangerText),
          const SizedBox(width: 4),
          Text(
            _autoSaveStatus == AutoSaveStatus.saving
                ? 'Saving...'
                : _autoSaveStatus == AutoSaveStatus.saved
                    ? 'Saved'
                    : 'Save failed',
            style: TextStyle(
              fontSize: 11,
              color: _autoSaveStatus == AutoSaveStatus.saving
                  ? AppColors.textTertiary
                  : _autoSaveStatus == AutoSaveStatus.saved
                      ? AppColors.closedText
                      : AppColors.dangerText,
            ),
          ),
        ],
        if (showUndo) ...[
          if (showStatus) const SizedBox(width: 6),
          GestureDetector(
            onTap: _undoChanges,
            child: Container(
              padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
              decoration: BoxDecoration(
                color: AppColors.bgSurface2,
                borderRadius: BorderRadius.circular(4),
                border: Border.all(color: AppColors.border2, width: 0.5),
              ),
              child: Text(
                'Undo',
                style: TextStyle(
                  fontSize: 11,
                  fontWeight: FontWeight.w500,
                  color: AppColors.accent,
                ),
              ),
            ),
          ),
        ],
      ],
    );
  }

  bool get _canUndo {
    if (_originalSnapshot == null || widget.workOrder == null) return false;
    final current = _formSnapshot();
    for (final key in current.keys) {
      final a = current[key];
      final b = _originalSnapshot![key];
      if (a is List && b is List) {
        if (a.length != b.length || a.join(',') != b.join(',')) return true;
      } else if (a != b) {
        return true;
      }
    }
    return false;
  }

  void _undoChanges() {
    if (_originalSnapshot == null || widget.workOrder == null) return;
    _autoSaveTimer?.cancel();

    // Remove listeners temporarily to avoid multiple triggers while restoring
    clientController.removeListener(_onFormFieldChanged);
    descriptionController.removeListener(_onFormFieldChanged);
    locationController.removeListener(_onFormFieldChanged);
    mobileController.removeListener(_onFormFieldChanged);

    setState(() {
      clientController.text = widget.workOrder!.title;
      descriptionController.text = widget.workOrder!.description;
      locationController.text = widget.workOrder!.location;
      mobileController.text = widget.workOrder!.mobileNumber ?? '';
      selectedDepartment = widget.workOrder!.department;
      selectedDepartmentId = widget.workOrder!.departmentId;
      selectedStatus = _allowedStatuses.contains(widget.workOrder!.status)
          ? widget.workOrder!.status
          : 'Pending';
      selectedType = _allowedTypes.contains(widget.workOrder!.type)
          ? widget.workOrder!.type
          : 'Technical';
      _selectedEmployeeIds =
          widget.workOrder!.assignedTechnicians.map((t) => t.id).toList();
      _autoSaveStatus = AutoSaveStatus.idle;
    });

    // Re-attach listeners
    clientController.addListener(_onFormFieldChanged);
    descriptionController.addListener(_onFormFieldChanged);
    locationController.addListener(_onFormFieldChanged);
    mobileController.addListener(_onFormFieldChanged);

    // Save the reverted state to the server if we had previously auto-saved
    if (_hasAutoSaved) {
      _performAutoSave();
    }
  }

  Future<void> _loadEmployees({String? departmentId}) async {
    final deptId = departmentId ?? (selectedDepartmentId.isNotEmpty ? selectedDepartmentId : null);
    final data = await _userService.fetchTechnicians(departmentId: deptId);
    if (!mounted) return;
    setState(() {
      _employees = data;
      if (widget.workOrder != null) {
        _selectedEmployeeIds =
            widget.workOrder!.assignedTechnicians.map((t) => t.id).toList();
        // Update snapshots now that technician IDs are loaded
        final snapshot = _formSnapshot();
        _originalSnapshot = Map.from(snapshot);
        _lastSavedSnapshot = snapshot;
      }
    });
  }

  Future<void> _loadComments() async {
    if (widget.workOrder == null) return;
    if (!_refreshing) {
      setState(() => _commentsLoading = true);
    }
    try {
      final comments = await _service.fetchComments(widget.workOrder!.id);
      final attachments = await _service.fetchAttachments(widget.workOrder!.id);
      if (mounted) {
        setState(() {
          _comments = comments;
          _attachments = attachments;
        });
        WidgetsBinding.instance.addPostFrameCallback((_) {
          if (_activityScrollCtrl.hasClients) {
            _activityScrollCtrl.animateTo(
              _activityScrollCtrl.position.maxScrollExtent,
              duration: const Duration(milliseconds: 300),
              curve: Curves.easeOut,
            );
          }
        });
      }
    } catch (_) {}
    if (mounted) {
      setState(() {
        _commentsLoading = false;
        _refreshing = false;
      });
    }
  }

  Future<void> _pickAttachment() async {
    final file = await _service.pickAttachment();
    if (file != null && mounted) {
      setState(() => _pendingAttachment = file);
    }
  }

  void _removePendingAttachment() {
    setState(() => _pendingAttachment = null);
  }

  Future<void> _deleteAttachment(WorkOrderAttachment attachment) async {
    final success = await _service.deleteAttachment(
      widget.workOrder!.id,
      attachment.id,
    );
    if (success && mounted) {
      setState(() {
        _attachments.removeWhere((a) => a.id == attachment.id);
      });
    }
  }

  Future<void> _sendComment() async {
    final text = _commentCtrl.text.trim();
    final hasAttachment = _pendingAttachment != null;
    if (text.isEmpty && !hasAttachment) return;
    if (_sending) return;

    final email = Supabase.instance.client.auth.currentUser?.email ?? '';
    final name = email.split('@').first;

    setState(() => _sending = true);
    try {
      String? uploadedFileName;
      if (_pendingAttachment != null) {
        final attachment = await _service.uploadAttachment(
          workOrderId: widget.workOrder!.id,
          file: _pendingAttachment!,
        );
        if (attachment != null && mounted) {
          uploadedFileName = _pendingAttachment!.name;
          setState(() {
            _attachments = [..._attachments, attachment];
          });
        }
      }

      // Send a single comment (with file info if uploaded, or just text)
      final commentBody = text.isNotEmpty
          ? text
          : (uploadedFileName != null ? 'uploaded a file: $uploadedFileName' : '');
      final commentType = text.isNotEmpty ? 'comment' : 'system';

      if (commentBody.isNotEmpty) {
        final comment = await _service.addComment(
          workOrderId: widget.workOrder!.id,
          authorEmail: email,
          authorName: name,
          body: commentBody,
          type: commentType,
        );
        if (comment != null && mounted) {
          _commentCtrl.clear();
          setState(() => _comments = [..._comments, comment]);
          WidgetsBinding.instance.addPostFrameCallback((_) {
            if (_activityScrollCtrl.hasClients) {
              _activityScrollCtrl.animateTo(
                _activityScrollCtrl.position.maxScrollExtent,
                duration: const Duration(milliseconds: 300),
                curve: Curves.easeOut,
              );
            }
          });
        }
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(SnackBar(
          content: Text('Failed to send: $e'),
          backgroundColor: AppColors.dangerText,
          behavior: SnackBarBehavior.floating,
        ));
      }
    }
    if (mounted) {
      setState(() {
        _sending = false;
        _pendingAttachment = null;
      });
    }
  }

  Future<void> submit() async {
    _autoSaveTimer?.cancel();
    // Reporters can CREATE new work orders but cannot EDIT existing ones
    final isNewWorkOrder = widget.workOrder == null;
    if (_isReporter && !isNewWorkOrder) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Reporter cannot edit work orders'),
          backgroundColor: AppColors.dangerText,
          behavior: SnackBarBehavior.floating,
        ),
      );
      return;
    }
    if (!_formKey.currentState!.validate()) return;
    if (selectedDepartmentId.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(const SnackBar(
        content: Text('Please select a department'),
        backgroundColor: Colors.orange,
        behavior: SnackBarBehavior.floating,
      ));
      return;
    }
    try {
      final now = DateTime.now().toUtc().toIso8601String();
      final newWorkOrder = WorkOrder(
        id: widget.workOrder?.id ?? '',
        jobNo: jobNoController.text.trim(),
        title: clientController.text.trim(),
        status: selectedStatus,
        description: descriptionController.text.trim(),
        location: locationController.text.trim(),
        mobileNumber: mobileController.text.trim(),
        departmentName: selectedDepartment,
        departmentId: selectedDepartmentId,
        type: selectedType,
        dateCreated: widget.workOrder?.dateCreated ?? now,
        dateModified: now,
        assignedTechnicians: _selectedEmployeeIds
            .map((id) => TechnicianAssignment(id: id, fullName: ''))
            .toList(),
      );

      if (widget.workOrder == null) {
        try {
          final createdOrder = await _service.addWorkOrder(newWorkOrder);
          if (!mounted) return;
          Navigator.pop(context, createdOrder);
        } catch (e) {
          if (!mounted) return;
          ScaffoldMessenger.of(context).showSnackBar(SnackBar(
            content: Text('Failed to create work order: $e'),
            backgroundColor: AppColors.dangerText,
            behavior: SnackBarBehavior.floating,
            duration: Duration(seconds: 5),
          ));
          return;
        }
      } else {
        try {
          await _service.updateWorkOrder(newWorkOrder);
          if (!mounted) return;
          Navigator.pop(context, "updated");
        } catch (e) {
          if (!mounted) return;
          ScaffoldMessenger.of(context).showSnackBar(SnackBar(
            content: Text('Failed to update work order: $e'),
            backgroundColor: AppColors.dangerText,
            behavior: SnackBarBehavior.floating,
            duration: Duration(seconds: 5),
          ));
        }
      }
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(
        content: Text('Error: $e'),
        backgroundColor: AppColors.dangerText,
