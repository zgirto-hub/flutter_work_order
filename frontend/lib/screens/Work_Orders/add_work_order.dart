import 'package:flutter/material.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import '../../models/work_order.dart';
import '../../models/work_order_comment.dart';
import '../../services/work_order_service.dart';
import '../../models/employee.dart';
import '../../services/employee_service.dart';
import '../../models/employee_assignment.dart';
import '../../widgets/employee_selector.dart';
import '../../theme/app_theme.dart';

class AddWorkOrderScreen extends StatefulWidget {
  final WorkOrder? workOrder;
  final String? autoGeneratedJobNo;
  final String? prefillTitle;
  final String? prefillLocation;
  final String? sourceRequestId;

  const AddWorkOrderScreen({
    super.key,
    this.workOrder,
    this.autoGeneratedJobNo,
    this.prefillTitle,
    this.prefillLocation,
    this.sourceRequestId,
  });

  @override
  State<AddWorkOrderScreen> createState() => _AddWorkOrderScreenState();
}

class _AddWorkOrderScreenState extends State<AddWorkOrderScreen> {
  final EmployeeService _employeeService = EmployeeService();
  final WorkOrderService _service = WorkOrderService();
  final _formKey = GlobalKey<FormState>();

  List<Employee> _employees = [];
  List<String> _selectedEmployeeIds = [];

  final TextEditingController jobNoController = TextEditingController();
  final TextEditingController clientController = TextEditingController();
  final TextEditingController descriptionController = TextEditingController();
  final TextEditingController locationController = TextEditingController();

  String selectedStatus = "Pending";
  String selectedType = "Technical";

  // Activity tab state
  int _tabIndex = 0;
  List<WorkOrderComment> _comments = [];
  bool _commentsLoading = false;
  bool _sending = false;
  final TextEditingController _commentCtrl = TextEditingController();
  final ScrollController _activityScrollCtrl = ScrollController();

  static const List<String> _allowedTypes = [
    "Technical",
    "Inspection",
    "Other",
  ];

  static const List<String> _allowedStatuses = [
    "Pending",
    "In Progress",
    "Closed",
  ];

  @override
  void initState() {
    super.initState();
    _loadEmployees();
    if (widget.workOrder != null) {
      jobNoController.text = widget.workOrder!.jobNo;
      clientController.text = widget.workOrder!.Title;
      descriptionController.text = widget.workOrder!.description;
      locationController.text = widget.workOrder!.location;
      selectedStatus = _allowedStatuses.contains(widget.workOrder!.status)
          ? widget.workOrder!.status
          : "Pending";
      selectedType = _allowedTypes.contains(widget.workOrder!.type)
          ? widget.workOrder!.type
          : "Technical";
      _loadComments();
    } else {
      jobNoController.text = widget.autoGeneratedJobNo ?? "";
      if (widget.prefillTitle != null) clientController.text = widget.prefillTitle!;
      if (widget.prefillLocation != null) locationController.text = widget.prefillLocation!;
    }
  }

  @override
  void dispose() {
    jobNoController.dispose();
    clientController.dispose();
    descriptionController.dispose();
    locationController.dispose();
    _commentCtrl.dispose();
    _activityScrollCtrl.dispose();
    super.dispose();
  }

  Future<void> _loadEmployees() async {
    final data = await _employeeService.fetchEmployees();
    setState(() {
      _employees = data;
      if (widget.workOrder != null) {
        _selectedEmployeeIds =
            widget.workOrder!.assignedEmployees.map((emp) => emp.id).toList();
      }
    });
  }

  Future<void> _loadComments() async {
    if (widget.workOrder == null) return;
    setState(() => _commentsLoading = true);
    try {
      final comments = await _service.fetchComments(widget.workOrder!.id);
      if (mounted) setState(() => _comments = comments);
    } catch (_) {}
    if (mounted) setState(() => _commentsLoading = false);
  }

  Future<void> _sendComment() async {
    final text = _commentCtrl.text.trim();
    if (text.isEmpty || _sending) return;
    final email = Supabase.instance.client.auth.currentUser?.email ?? '';
    final name = email.split('@').first;

    setState(() => _sending = true);
    try {
      final comment = await _service.addComment(
        workOrderId: widget.workOrder!.id,
        authorEmail: email,
        authorName: name,
        body: text,
      );
      if (comment != null && mounted) {
        _commentCtrl.clear();
        setState(() => _comments = [..._comments, comment]);
        WidgetsBinding.instance.addPostFrameCallback((_) {
          if (_activityScrollCtrl.hasClients) {
            _activityScrollCtrl.animateTo(
              _activityScrollCtrl.position.maxScrollExtent,
              duration: const Duration(milliseconds: 300),
              curve: Curves.easeOut,
            );
          }
        });
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(SnackBar(
          content: Text('Failed to send: $e'),
          backgroundColor: AppColors.dangerText,
          behavior: SnackBarBehavior.floating,
        ));
      }
    }
    if (mounted) setState(() => _sending = false);
  }

  Future<void> submit() async {
    if (!_formKey.currentState!.validate()) return;
    try {
      final now = DateTime.now().toIso8601String();
      final newWorkOrder = WorkOrder(
        id: widget.workOrder?.id ?? '',
        jobNo: jobNoController.text.trim(),
        Title: clientController.text.trim(),
        status: selectedStatus,
        description: descriptionController.text.trim(),
        location: locationController.text.trim(),
        type: selectedType,
        dateCreated: widget.workOrder?.dateCreated ?? now,
        dateModified: now,
        assignedEmployees: _selectedEmployeeIds
            .map((id) => EmployeeAssignment(id: id, fullName: ''))
            .toList(),
      );

      if (widget.workOrder == null) {
        final createdOrder = await _service.addWorkOrder(
          newWorkOrder,
          sourceRequestId: widget.sourceRequestId,
        );
        if (!mounted) return;
        Navigator.pop(context, createdOrder);
      } else {
        await _service.updateWorkOrder(newWorkOrder);
        if (!mounted) return;
        Navigator.pop(context, "updated");
      }
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(SnackBar(
        content: Text('Error: ${e.toString()}'),
        backgroundColor: AppColors.dangerText,
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
      ));
    }
  }

  IconData _typeIcon(String type) {
    switch (type) {
      case 'Inspection':
        return Icons.checklist_rounded;
      case 'Technical':
        return Icons.build_outlined;
      default:
        return Icons.work_outline_rounded;
    }
  }

  Color _typeColor(String type) {
    switch (type) {
      case 'Inspection':
        return AppColors.inProgressText;
      case 'Technical':
        return AppColors.accent;
      default:
        return AppColors.textSecondary;
    }
  }

  @override
  Widget build(BuildContext context) {
    final isEditing = widget.workOrder != null;

    return Scaffold(
      backgroundColor: AppColors.bgPrimary,
      body: SafeArea(
        child: Column(
          children: [
            // ── Header ────────────────────────────────────────────
            Container(
              color: AppColors.bgSurface,
              padding: const EdgeInsets.fromLTRB(16, 12, 16, 0),
              child: Column(
                children: [
                  Row(
                    children: [
                      GestureDetector(
                        onTap: () => Navigator.pop(context),
                        child: Container(
                          width: 34,
                          height: 34,
                          decoration: BoxDecoration(
                            color: AppColors.bgSurface2,
                            borderRadius: BorderRadius.circular(9),
                            border: Border.all(
                                color: AppColors.border2, width: 0.5),
                          ),
                          child: const Icon(Icons.arrow_back_rounded,
                              size: 16, color: AppColors.textSecondary),
                        ),
                      ),
                      const SizedBox(width: 12),
                      Expanded(
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Text(
                              isEditing
                                  ? widget.workOrder!.Title
                                  : 'New Work Order',
                              style: const TextStyle(
                                fontSize: 16,
                                fontWeight: FontWeight.w600,
                                color: AppColors.textPrimary,
                                letterSpacing: -0.3,
                              ),
                              maxLines: 1,
                              overflow: TextOverflow.ellipsis,
                            ),
                            if (isEditing) ...[
                              const SizedBox(height: 1),
                              Text(
                                widget.workOrder!.jobNo,
                                style: const TextStyle(
                                    fontSize: 11,
                                    color: AppColors.textTertiary),
                              ),
                            ],
                          ],
                        ),
                      ),
                      if (isEditing)
                        _StatusPill(status: widget.workOrder!.status),
                    ],
                  ),

                  // Tabs (edit mode only)
                  if (isEditing) ...[
                    const SizedBox(height: 10),
                    Row(
                      children: [
                        _Tab(
                          label: 'Details',
                          active: _tabIndex == 0,
                          onTap: () => setState(() => _tabIndex = 0),
                        ),
                        _Tab(
                          label: 'Activity',
                          active: _tabIndex == 1,
                          badge: _comments
                              .where((c) => c.type == 'comment')
                              .length,
                          onTap: () => setState(() => _tabIndex = 1),
                        ),
                      ],
                    ),
                  ] else
                    const SizedBox(height: 12),
                ],
              ),
            ),

            const Divider(height: 0, thickness: 0.5, color: AppColors.border),

            // ── Body ──────────────────────────────────────────────
            Expanded(
              child: isEditing && _tabIndex == 1
                  ? _buildActivityTab()
                  : _buildDetailsTab(),
            ),

            // ── Compose bar (activity tab only) ───────────────────
            if (isEditing && _tabIndex == 1) _buildComposeBar(),
          ],
        ),
      ),
    );
  }

  Widget _buildDetailsTab() {
    return SingleChildScrollView(
      padding: const EdgeInsets.all(16),
      child: Form(
        key: _formKey,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            TextFormField(
              controller: jobNoController,
              readOnly: true,
              decoration: const InputDecoration(
                labelText: "Job No",
                hintText: "Auto-generated",
                filled: true,
              ),
            ),
            const SizedBox(height: 10),
            TextFormField(
              controller: clientController,
              decoration: const InputDecoration(labelText: "Title"),
              validator: (v) => v!.isEmpty ? "Enter Title" : null,
            ),
            const SizedBox(height: 10),
            DropdownButtonFormField<String>(
              value: selectedStatus,
              items: _allowedStatuses
                  .map((s) => DropdownMenuItem(value: s, child: Text(s)))
                  .toList(),
              onChanged: (v) => setState(() => selectedStatus = v!),
              decoration: const InputDecoration(labelText: "Status"),
            ),
            const SizedBox(height: 10),
            TextFormField(
              controller: locationController,
              decoration: const InputDecoration(labelText: "Location"),
              validator: (v) => v!.isEmpty ? "Enter Location" : null,
            ),
            const SizedBox(height: 10),

            // ── Type dropdown with icons ───────────────────────────
            DropdownButtonFormField<String>(
              value: selectedType,
              items: _allowedTypes.map((type) {
                return DropdownMenuItem(
                  value: type,
                  child: Row(
                    children: [
                      Icon(_typeIcon(type),
                          size: 16, color: _typeColor(type)),
                      const SizedBox(width: 8),
                      Text(type),
                    ],
                  ),
                );
              }).toList(),
              onChanged: (v) => setState(() => selectedType = v!),
              decoration: const InputDecoration(labelText: "Type"),
            ),
            const SizedBox(height: 10),

            TextFormField(
              controller: descriptionController,
              decoration: const InputDecoration(labelText: "Description"),
              maxLines: 3,
            ),
            const SizedBox(height: 25),
            const Text(
              "Assign Employees",
              style:
                  TextStyle(fontSize: 16, fontWeight: FontWeight.w600),
            ),
            const SizedBox(height: 10),
            ElevatedButton.icon(
              icon: const Icon(Icons.people),
              label: const Text("Select Employees"),
              onPressed: _openEmployeeSelector,
            ),
            const SizedBox(height: 10),
            Wrap(
              spacing: 8,
              children: _employees
                  .where((e) => _selectedEmployeeIds.contains(e.id))
                  .map((employee) => Chip(
                        label: Text(employee.fullName),
                        deleteIcon: const Icon(Icons.close),
                        onDeleted: () => setState(() =>
                            _selectedEmployeeIds.remove(employee.id)),
                      ))
                  .toList(),
            ),
            const SizedBox(height: 25),
            ElevatedButton(
              onPressed: submit,
              child: Text(widget.workOrder == null
                  ? "Add Work Order"
                  : "Save Changes"),
            ),
            if (widget.workOrder != null) ...[
              const SizedBox(height: 12),
              TextButton.icon(
                icon: const Icon(Icons.delete_outline,
                    color: Colors.red, size: 18),
                label: const Text("Delete work order",
                    style: TextStyle(color: Colors.red)),
                onPressed: _confirmDelete,
              ),
            ],
          ],
        ),
      ),
    );
  }

  Widget _buildActivityTab() {
    if (_commentsLoading) {
      return const Center(
        child: CircularProgressIndicator(
            color: AppColors.accent, strokeWidth: 2),
      );
    }

    if (_comments.isEmpty) {
      return const Center(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Icon(Icons.chat_bubble_outline_rounded,
                size: 44, color: AppColors.bgSurface3),
            SizedBox(height: 12),
            Text('No activity yet',
                style: TextStyle(
                    fontSize: 14, color: AppColors.textTertiary)),
            SizedBox(height: 4),
            Text('Be the first to add a comment',
                style: TextStyle(
                    fontSize: 12, color: AppColors.textTertiary)),
          ],
        ),
      );
    }

    return ListView.builder(
      controller: _activityScrollCtrl,
      padding: const EdgeInsets.fromLTRB(16, 14, 16, 16),
      itemCount: _comments.length,
      itemBuilder: (context, i) {
        final comment = _comments[i];
        final isLast = i == _comments.length - 1;
        return _ActivityItem(
          comment: comment,
          isLast: isLast,
          currentUserEmail:
              Supabase.instance.client.auth.currentUser?.email ?? '',
        );
      },
    );
  }

  Widget _buildComposeBar() {
    final currentUser =
        Supabase.instance.client.auth.currentUser?.email ?? '';
    final initials = currentUser.split('@').first;
    final abbr = initials.length >= 2
        ? initials.substring(0, 2).toUpperCase()
        : initials.toUpperCase();

    return Container(
      color: AppColors.bgSurface,
      padding: EdgeInsets.fromLTRB(
          12, 10, 12, MediaQuery.of(context).viewInsets.bottom + 12),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.end,
        children: [
          // Avatar
          Container(
            width: 28,
            height: 28,
            decoration: const BoxDecoration(
              color: AppColors.accentBg,
              shape: BoxShape.circle,
            ),
            child: Center(
              child: Text(abbr,
                  style: const TextStyle(
                      fontSize: 10,
                      fontWeight: FontWeight.w500,
                      color: AppColors.accent)),
            ),
          ),
          const SizedBox(width: 8),
          // Input
          Expanded(
            child: Container(
              decoration: BoxDecoration(
                color: AppColors.bgSurface2,
                borderRadius: BorderRadius.circular(20),
                border:
                    Border.all(color: AppColors.border, width: 0.5),
              ),
              child: TextField(
                controller: _commentCtrl,
                maxLines: null,
                keyboardType: TextInputType.multiline,
                textInputAction: TextInputAction.newline,
                style: const TextStyle(
                    fontSize: 13, color: AppColors.textPrimary),
                decoration: const InputDecoration(
                  hintText: 'Add a comment…',
                  hintStyle: TextStyle(
                      fontSize: 13, color: AppColors.textTertiary),
                  border: InputBorder.none,
                  enabledBorder: InputBorder.none,
                  focusedBorder: InputBorder.none,
                  contentPadding:
                      EdgeInsets.symmetric(horizontal: 14, vertical: 9),
                ),
              ),
            ),
          ),
          const SizedBox(width: 8),
          // Send button
          GestureDetector(
            onTap: _sending ? null : _sendComment,
            child: Container(
              width: 34,
              height: 34,
              decoration: const BoxDecoration(
                color: AppColors.accent,
                shape: BoxShape.circle,
              ),
              child: _sending
                  ? const Padding(
                      padding: EdgeInsets.all(9),
                      child: CircularProgressIndicator(
                          strokeWidth: 1.5, color: Colors.white),
                    )
                  : const Icon(Icons.send_rounded,
                      size: 15, color: Colors.white),
            ),
          ),
        ],
      ),
    );
  }

  Future<void> _confirmDelete() async {
    final confirm = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text("Delete Work Order"),
        content:
            const Text("Are you sure you want to delete this work order?"),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text("Cancel"),
          ),
          TextButton(
            onPressed: () => Navigator.pop(context, true),
            child: const Text("Delete",
                style: TextStyle(color: Colors.red)),
          ),
        ],
      ),
    );
    if (confirm == true && widget.workOrder != null) {
      await _service.deleteWorkOrder(widget.workOrder!.id);
      if (!mounted) return;
      Navigator.pop(context, "deleted");
    }
  }

  void _openEmployeeSelector() {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      builder: (context) => EmployeeSelector(
        employees: _employees,
        selectedIds: _selectedEmployeeIds,
        onChanged: (ids) => setState(() => _selectedEmployeeIds = ids),
      ),
    );
  }
}

// ── Tab ───────────────────────────────────────────────────────────────────────

class _Tab extends StatelessWidget {
  final String label;
  final bool active;
  final int badge;
  final VoidCallback onTap;

  const _Tab({
    required this.label,
    required this.active,
    required this.onTap,
    this.badge = 0,
  });

  @override
  Widget build(BuildContext context) {
    return GestureDetector(
      onTap: onTap,
      child: Container(
        padding: const EdgeInsets.only(bottom: 10),
        margin: const EdgeInsets.only(right: 20),
        decoration: BoxDecoration(
          border: Border(
            bottom: BorderSide(
              color: active ? AppColors.accent : Colors.transparent,
              width: 2,
            ),
          ),
        ),
        child: Row(
          mainAxisSize: MainAxisSize.min,
          children: [
            Text(
              label,
              style: TextStyle(
                fontSize: 13,
                fontWeight: FontWeight.w500,
                color:
                    active ? AppColors.accent : AppColors.textSecondary,
              ),
            ),
            if (badge > 0) ...[
              const SizedBox(width: 5),
              Container(
                padding:
                    const EdgeInsets.symmetric(horizontal: 5, vertical: 1),
                decoration: BoxDecoration(
                  color: active
                      ? AppColors.accent
                      : AppColors.bgSurface3,
                  borderRadius: BorderRadius.circular(8),
                ),
                child: Text(
                  '$badge',
                  style: TextStyle(
                    fontSize: 10,
                    fontWeight: FontWeight.w500,
                    color: active ? Colors.white : AppColors.textTertiary,
                  ),
                ),
              ),
            ],
          ],
        ),
      ),
    );
  }
}

// ── Status Pill ───────────────────────────────────────────────────────────────

class _StatusPill extends StatelessWidget {
  final String status;
  const _StatusPill({required this.status});

  @override
  Widget build(BuildContext context) {
    Color bg, fg;
    switch (status) {
      case 'In Progress':
        bg = AppColors.inProgressBg;
        fg = AppColors.inProgressText;
        break;
      case 'Closed':
        bg = AppColors.closedBg;
        fg = AppColors.closedText;
        break;
      default:
        bg = AppColors.pendingBg;
        fg = AppColors.pendingText;
    }
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
      decoration:
          BoxDecoration(color: bg, borderRadius: BorderRadius.circular(20)),
      child: Text(status,
          style: TextStyle(
              fontSize: 11, fontWeight: FontWeight.w500, color: fg)),
    );
  }
}

// ── Activity Item ─────────────────────────────────────────────────────────────

class _ActivityItem extends StatelessWidget {
  final WorkOrderComment comment;
  final bool isLast;
  final String currentUserEmail;

  const _ActivityItem({
    required this.comment,
    required this.isLast,
    required this.currentUserEmail,
  });

  Color get _avatarBg {
    if (comment.type == 'system') return AppColors.bgSurface2;
    final colors = [
      const Color(0xFFEEEDFE),
      const Color(0xFFE1F5EE),
      const Color(0xFFF5EBE6),
      const Color(0xFFE8F0FB),
    ];
    return colors[comment.authorName.hashCode.abs() % colors.length];
  }

  Color get _avatarFg {
    if (comment.type == 'system') return AppColors.textTertiary;
    final colors = [
      const Color(0xFF3C3489),
      const Color(0xFF085041),
      const Color(0xFF993C1D),
      const Color(0xFF0C447C),
    ];
    return colors[comment.authorName.hashCode.abs() % colors.length];
  }

  @override
  Widget build(BuildContext context) {
    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        // Left: avatar + connecting line
        SizedBox(
          width: 34,
          child: Column(
            children: [
              Container(
                width: 30,
                height: 30,
                decoration: BoxDecoration(
                  color: _avatarBg,
                  shape: BoxShape.circle,
                ),
                child: Center(
                  child: comment.type == 'system'
                      ? const Icon(Icons.settings_outlined,
                          size: 14, color: AppColors.textTertiary)
                      : Text(comment.initials,
                          style: TextStyle(
                              fontSize: 11,
                              fontWeight: FontWeight.w500,
                              color: _avatarFg)),
                ),
              ),
              if (!isLast)
                Container(
                  width: 1,
                  height: 32,
                  margin: const EdgeInsets.symmetric(vertical: 4),
                  color: AppColors.border,
                ),
            ],
          ),
        ),
        const SizedBox(width: 10),
        // Right: content
        Expanded(
          child: Padding(
            padding: EdgeInsets.only(bottom: isLast ? 0 : 6),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                // Meta row
                Row(
                  children: [
                    Text(
                      comment.authorEmail == currentUserEmail
                          ? 'You'
                          : comment.authorName,
                      style: const TextStyle(
                          fontSize: 12,
                          fontWeight: FontWeight.w500,
                          color: AppColors.textPrimary),
                    ),
                    const SizedBox(width: 6),
                    Text(comment.formattedTime,
                        style: const TextStyle(
                            fontSize: 11,
                            color: AppColors.textSecondary)),
                    const SizedBox(width: 6),
                    if (comment.type == 'comment')
                      Container(
                        padding: const EdgeInsets.symmetric(
                            horizontal: 5, vertical: 1),
                        decoration: BoxDecoration(
                          color: AppColors.accentBg,
                          borderRadius: BorderRadius.circular(6),
                        ),
                        child: const Text('comment',
                            style: TextStyle(
                                fontSize: 10,
                                fontWeight: FontWeight.w500,
                                color: AppColors.accent)),
                      )
                    else if (comment.type == 'status_change')
                      Container(
                        padding: const EdgeInsets.symmetric(
                            horizontal: 5, vertical: 1),
                        decoration: BoxDecoration(
                          color: AppColors.inProgressBg,
                          borderRadius: BorderRadius.circular(6),
                        ),
                        child: const Text('status',
                            style: TextStyle(
                                fontSize: 10,
                                fontWeight: FontWeight.w500,
                                color: AppColors.inProgressText)),
                      ),
                  ],
                ),
                const SizedBox(height: 4),
                // Body
                if (comment.type == 'status_change' &&
                    comment.meta != null) ...[
                  Row(
                    children: [
                      _StatusBadge(
                          status: comment.meta!['from'] as String? ?? ''),
                      const Padding(
                        padding: EdgeInsets.symmetric(horizontal: 6),
                        child: Icon(Icons.arrow_forward_rounded,
                            size: 12, color: AppColors.textTertiary),
                      ),
                      _StatusBadge(
                          status: comment.meta!['to'] as String? ?? ''),
                    ],
                  ),
                ] else
                  Text(
                    comment.body,
                    style: TextStyle(
                      fontSize: 13,
                      color: comment.type == 'system'
                          ? AppColors.textSecondary
                          : AppColors.textPrimary,
                      fontStyle: comment.type == 'system'
                          ? FontStyle.italic
                          : FontStyle.normal,
                      height: 1.5,
                    ),
                  ),
